async def _pg_connect():
    import asyncpg

    candidates = [
        os.environ.get("RAGLAN_PGCONN"),
        "postgresql://postgres:postgres@localhost:5432/raglan_test",
        "postgresql://postgres:123456@localhost:5432/raglan_test",
    ]
    for cs in candidates:
        if cs is None:
            continue
        try:
            return await asyncpg.create_pool(cs, min_size=1, max_size=2, command_timeout=10)
        except Exception:
            pass
    return None


async def _pg_setup(pool, chunks):
    await pool.execute("CREATE EXTENSION IF NOT EXISTS vector")
    await pool.execute(f"DROP TABLE IF EXISTS {_TABLE}")
    await pool.execute(
        f"CREATE TABLE {_TABLE} ("
        "  chunk_id TEXT PRIMARY KEY,"
        "  parent_id TEXT NOT NULL DEFAULT '',"
        "  content TEXT NOT NULL,"
        "  embedding vector(384),"
        "  metadata JSONB DEFAULT '{}'"
        ")"
    )
    for c in chunks:
        emb_str = "[" + ",".join(f"{x:.8g}" for x in c["embedding"]) + "]"
        await pool.execute(
            f"INSERT INTO {_TABLE} VALUES ($1,$2,$3,$4::vector,$5::jsonb)",
            c["chunk_id"],
            c["parent_id"],
            c["content"],
            emb_str,
            json.dumps(c["metadata"]),
        )
    await pool.execute(
        f"CREATE INDEX IF NOT EXISTS e2e_idx ON {_TABLE} "
        "USING ivfflat (embedding vector_cosine_ops) WITH (lists = 1)"
    )


async def _pg_search(pool, embedding, top_k=5):
    emb_str = "[" + ",".join(f"{x:.8g}" for x in embedding) + "]"
    rows = await pool.fetch(
        f"SELECT chunk_id, content, metadata, parent_id, "
        f"1 - (embedding <=> $1::vector) AS score "
        f"FROM {_TABLE} ORDER BY embedding <=> $1::vector LIMIT $2",
        emb_str,
        top_k,
    )
    results = []
    for r in rows:
        meta = r[2] if isinstance(r[2], dict) else json.loads(r[2])
        meta["parent_id"] = r[3]
        results.append(
            {"chunk_id": r[0], "content": r[1][:120], "metadata": meta, "score": float(r[4])}
        )
    return results


class TestPgvectorPrecomputed:
    @pytest.fixture
    async def pg_pool(self, e2e_fixtures):
        pool = await _pg_connect()
        if pool is None:
            pytest.skip("PostgreSQL not available")
        try:
            await pool.execute("CREATE EXTENSION IF NOT EXISTS vector")
        except Exception as e:
            if "duplicate key" not in str(e) and "already exists" not in str(e):
                raise
        await pool.execute(f"DROP TABLE IF EXISTS {_TABLE}")
        await pool.execute(
            f"CREATE TABLE {_TABLE} ("
            "  chunk_id TEXT PRIMARY KEY,"
            "  parent_id TEXT NOT NULL DEFAULT '',"
            "  content TEXT NOT NULL,"
            "  embedding vector(384),"
            "  metadata JSONB DEFAULT '{}'"
            ")"
        )
        for c in e2e_fixtures["chunks"]:
            emb_str = "[" + ",".join(f"{x:.8g}" for x in c["embedding"]) + "]"
            await pool.execute(
                f"INSERT INTO {_TABLE} VALUES ($1,$2,$3,$4::vector,$5::jsonb)",
                c["chunk_id"],
                c["parent_id"],
                c["content"],
                emb_str,
                json.dumps(c["metadata"]),
            )
        yield pool
        await pool.execute(f"DROP TABLE IF EXISTS {_TABLE}")
        await pool.close()

    @pytest.mark.asyncio
    @pytest.mark.parametrize("q", range(7))
    async def test_search(self, pg_pool, e2e_fixtures, q):
        query_data = e2e_fixtures["queries"][q]
        results = await _pg_search(pg_pool, query_data["embedding"], top_k=3)
        assert len(results) >= 1, f"No results for '{query_data['label']}'"
        assert results[0]["score"] > 0

    @pytest.mark.asyncio
    async def test_variant_search(self, pg_pool, e2e_fixtures):
        """Each query variant should also return relevant results."""
        query_data = e2e_fixtures["queries"][0]  # "chunking strategies"
        for i, vemb in enumerate(query_data["variant_embeddings"]):
            results = await _pg_search(pg_pool, vemb, top_k=3)
            assert len(results) >= 1, f"Variant {i} of '{query_data['label']}' got no results"

    @pytest.mark.asyncio
    async def test_parent_child_links(self, pg_pool, e2e_fixtures):
        """Child chunks reference their parent via parent_id."""
        query_data = e2e_fixtures["queries"][1]  # "embedding models"
        results = await _pg_search(pg_pool, query_data["embedding"], top_k=5)
        children = [r for r in results if r["metadata"].get("type") == "child"]
        assert len(children) >= 1
        for c in children:
            assert c["metadata"].get("parent_id", "").startswith("parent_")


