class TestCrossBackendConsistency:
    @pytest.fixture
    async def all_backends(self, e2e_fixtures):
        """Set up all three backends once (per-test for event loop safety)."""
        pool = await _pg_connect()
        if pool:
            await _pg_setup(pool, e2e_fixtures["chunks"])
        chroma = _chroma_setup(e2e_fixtures["chunks"])
        qdrant_path = await _qdrant_setup(e2e_fixtures["chunks"])
        yield {"pg": pool, "chroma": chroma, "qdrant_path": qdrant_path}
        if pool:
            await pool.execute(f"DROP TABLE IF EXISTS {_TABLE}")
            await pool.close()
        shutil.rmtree(qdrant_path, ignore_errors=True)

    @pytest.mark.asyncio
    async def test_top_results_overlap(self, all_backends, e2e_fixtures):
        """All three backends should agree on the best match."""
        query_data = e2e_fixtures["queries"][0]  # chunking strategies
        emb = query_data["embedding"]

        pg_ids = {r["chunk_id"] for r in await _pg_search(all_backends["pg"], emb, 3)}
        ch_ids = {r["chunk_id"] for r in _chroma_search(all_backends["chroma"], emb, 3)}
        qd = await _qdrant_search(all_backends["qdrant_path"], emb, 3)
        qd_ids = {r["chunk_id"] for r in qd}

        assert pg_ids & ch_ids, "pgvector and chromadb have no overlap"
        assert pg_ids & qd_ids, "pgvector and qdrant have no overlap"
        print(f"\n  pgvector: {pg_ids}\n  chromadb: {ch_ids}\n  qdrant:   {qd_ids}")
