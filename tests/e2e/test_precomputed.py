"""End-to-end pipeline test using pre-computed embeddings (no model, no network).

Loads fixture files generated by ``tests/generate_e2e_fixtures.py``, inserts
into pgvector / ChromaDB / Qdrant, and runs semantic search queries with
pre-computed query embeddings and variants.

Run::

    pytest tests/test_e2e_precomputed.py -v -s
"""

from __future__ import annotations

import asyncio
import contextlib
import json
import os
import shutil
import tempfile
import uuid
from pathlib import Path

import pytest

pytestmark = [pytest.mark.integration]

FIXTURES_DIR = Path(__file__).parent.parent / "fixtures"

# Unique suffix for xdist parallel workers (avoids table collisions)
_WORKER = os.environ.get("PYTEST_XDIST_WORKER", "").replace("gw", "w")
_TABLE = f"e2e_chunks{_WORKER}"


def _load_json(name: str) -> list[dict]:
    path = FIXTURES_DIR / name
    if not path.exists():
        pytest.skip(f"Fixture {name} not found — run: python tests/generate_e2e_fixtures.py")
    with open(path, encoding="utf-8") as f:
        return json.load(f)


