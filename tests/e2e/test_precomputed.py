@pytest.fixture(scope="session")
def e2e_fixtures():
    """Load pre-computed chunks and queries from JSON (no model needed)."""
    chunks = _load_json("e2e_chunks.json")
    queries = _load_json("e2e_queries.json")
    return {"chunks": chunks, "queries": queries}


