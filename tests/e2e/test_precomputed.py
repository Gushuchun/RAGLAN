def _chroma_setup(chunks):
    import chromadb

    client = chromadb.Client()
    with contextlib.suppress(Exception):
        client.delete_collection("e2e_raglan")
    col = client.create_collection("e2e_raglan", metadata={"hnsw:space": "cosine"})

    ids = [c["chunk_id"] for c in chunks]
    docs = [c["content"] for c in chunks]
    embs = [c["embedding"] for c in chunks]
    metas = [{**c["metadata"], "parent_id": c["parent_id"]} for c in chunks]

    for i in range(0, len(ids), 100):
        col.add(
            ids=ids[i : i + 100],
            documents=docs[i : i + 100],
            embeddings=embs[i : i + 100],
            metadatas=metas[i : i + 100],
        )
    return client


def _chroma_search(client, embedding, top_k=5):
    col = client.get_collection("e2e_raglan")
    resp = col.query(query_embeddings=[embedding], n_results=top_k)
    results = []
    if resp["ids"] and resp["ids"][0]:
        for i, cid in enumerate(resp["ids"][0]):
            dist = resp["distances"][0][i] if resp["distances"] else 0.0
            results.append(
                {
                    "chunk_id": cid,
                    "content": (resp["documents"][0][i] if resp["documents"] else "")[:120],
                    "metadata": resp["metadatas"][0][i] if resp["metadatas"] else {},
                    "score": round(1.0 - dist / 2.0, 4),
                }
            )
    return results


class TestChromaDBPrecomputed:
    @pytest.fixture
    def chroma_client(self, e2e_fixtures):
        return _chroma_setup(e2e_fixtures["chunks"])

    @pytest.mark.parametrize("q", range(7))
    def test_search(self, chroma_client, e2e_fixtures, q):
        query_data = e2e_fixtures["queries"][q]
        results = _chroma_search(chroma_client, query_data["embedding"], top_k=3)
        assert len(results) >= 1, f"No results for '{query_data['label']}'"
        assert results[0]["score"] > 0


