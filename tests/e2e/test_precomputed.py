async def _qdrant_setup(chunks):
    from qdrant_client import AsyncQdrantClient
    from qdrant_client.models import Distance, PointStruct, VectorParams

    tmpdir = tempfile.mkdtemp(prefix="raglan_qdrant_")
    client = AsyncQdrantClient(path=tmpdir)
    await client.create_collection(
        "e2e_raglan",
        vectors_config=VectorParams(size=384, distance=Distance.COSINE),
    )

    ns = uuid.UUID("6ba7b810-9dad-11d1-80b4-00c04fd430c8")
    points = []
    for c in chunks:
        points.append(
            PointStruct(
                id=str(uuid.uuid5(ns, c["chunk_id"])),
                vector=c["embedding"],
                payload={
                    "chunk_id": c["chunk_id"],
                    "parent_id": c["parent_id"],
                    "content": c["content"][:500],
                    "type": c["metadata"].get("type", ""),
                    "heading": c["metadata"].get("heading", ""),
                },
            )
        )
    await client.upsert("e2e_raglan", points)
    await client.close()
    return tmpdir


async def _qdrant_search(qdrant_path, embedding, top_k=5):
    from qdrant_client import AsyncQdrantClient
    from qdrant_client.models import NearestQuery

    client = AsyncQdrantClient(path=qdrant_path)
    resp = await client.query_points(
        "e2e_raglan",
        query=NearestQuery(nearest=embedding),
        limit=top_k,
        with_payload=True,
    )
    await client.close()
    results = []
    for p in resp.points:
        pl = p.payload or {}
        results.append(
            {
                "chunk_id": pl.get("chunk_id", str(p.id)),
                "content": pl.get("content", "")[:120],
                "metadata": {
                    "type": pl.get("type", ""),
                    "heading": pl.get("heading", ""),
                    "parent_id": pl.get("parent_id", ""),
                },
                "score": round(p.score or 0.0, 4),
            }
        )
    return results


class TestQdrantPrecomputed:
    @pytest.fixture
    def qdrant_path(self, e2e_fixtures):
        path = asyncio.run(_qdrant_setup(e2e_fixtures["chunks"]))
        yield path
        shutil.rmtree(path, ignore_errors=True)

    @pytest.mark.asyncio
    @pytest.mark.parametrize("q", range(7))
    async def test_search(self, qdrant_path, e2e_fixtures, q):
        query_data = e2e_fixtures["queries"][q]
        results = await _qdrant_search(qdrant_path, query_data["embedding"], top_k=3)
        assert len(results) >= 1, f"No results for '{query_data['label']}'"
        assert results[0]["score"] > 0


